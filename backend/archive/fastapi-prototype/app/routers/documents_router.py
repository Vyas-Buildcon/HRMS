@router.delete(
    "/{document_id}"
)
async def delete_document(
    document_id: str,
    user: dict = Depends(get_current_user),
):
    """
    Delete document metadata and the associated physical file.

    Only ADMIN / HR can delete documents.
    """

    if user["role"] not in {
        Role.ADMIN,
        Role.HR,
    }:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail="Only Admin or HR can delete documents.",
        )

    db = get_database()

    if not ObjectId.is_valid(document_id):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid document ID.",
        )

    document = await db.documents.find_one(
        {"_id": ObjectId(document_id)}
    )

    if not document:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Document not found.",
        )

    # Delete physical file.
    stored_filename = document.get(
        "storedFileName"
    )

    if stored_filename:
        file_path = UPLOAD_DIR / stored_filename

        if file_path.exists():
            try:
                file_path.unlink()
            except Exception:
                # Metadata should still be deleted even if
                # physical file cleanup fails.
                pass

    await db.documents.delete_one(
        {"_id": ObjectId(document_id)}
    )

    return {
        "success": True,
        "message": "Document deleted successfully.",
    }