def serialize_document(document: dict) -> dict:
    """
    Convert MongoDB document into the structure expected
    by src/types/documents.ts.
    """

    return {
        "_id": str(document["_id"]),
        "employeeId": document.get("employeeId", ""),
        "employeeName": document.get("employeeName", ""),
        "employeeCode": document.get("employeeCode", ""),
        "department": document.get("department", ""),
        "category": document.get("category", ""),
        "title": document.get("title", ""),
        "fileName": document.get("fileName", ""),
        "fileType": document.get("fileType", ""),
        "fileSize": document.get("fileSize", ""),
        "fileUrl": document.get("fileUrl"),
        "expiryDate": document.get("expiryDate"),
        "uploadedBy": document.get("uploadedBy", ""),
        "uploadedAt": document.get("uploadedAt", ""),
        "status": document.get("status", "PENDING"),
        "verifiedBy": document.get("verifiedBy"),
        "verifiedAt": document.get("verifiedAt"),
        "rejectionReason": document.get("rejectionReason"),
    }


def check_permission(
    user: dict,
    permission: Permission,
):
    if not has_permission(
        user["role"],
        permission,
    ):
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail=(
                f"Access denied. Role '{user['role'].value}' "
                f"does not have permission '{permission.value}'."
            ),
        )


async def get_employee(
    db,
    employee_id: str,
):
    """
    Retrieve employee information.

    The current FastAPI employee collection uses _id strings in the
    existing project, while MongoDB may contain ObjectId values.
    Therefore both forms are attempted.
    """

    employee = await db.employees.find_one(
        {"_id": employee_id}
    )

    if employee:
        return employee

    if ObjectId.is_valid(employee_id):
        employee = await db.employees.find_one(
            {"_id": ObjectId(employee_id)}
        )

    return employee


