@router.get("")
async def list_documents(
    category: Optional[str] = None,
    status_filter: Optional[str] = None,
    employeeId: Optional[str] = None,
    user: dict = Depends(get_current_user),
):
    """
    Return documents visible to the authenticated user.

    ADMIN / HR:
        Can view all documents.

    MANAGER:
        Can view documents belonging to their team/self according
        to the current employee data.

    EMPLOYEE:
        Can view only their own documents.
    """

    check_permission(
        user,
        Permission.DOCUMENT_VIEW_SELF,
    )

    db = get_database()

    query = {}

    if category and category != "ALL":
        query["category"] = category

    if status_filter and status_filter != "ALL":
        query["status"] = status_filter

    # Employees are restricted to their own documents.
    if user["role"] == Role.EMPLOYEE:
        query["uploadedUserId"] = user["user_id"]

    elif employeeId:
        query["employeeId"] = employeeId

    documents = []

    cursor = db.documents.find(query).sort(
        "uploadedAt",
        -1,
    )

    async for document in cursor:
        documents.append(
            serialize_document(document)
        )

    return {
        "total": len(documents),
        "documents": documents,
    }


# ---------------------------------------------------------
# POST /api/documents
# ---------------------------------------------------------

@router.post(
    "",
    status_code=status.HTTP_201_CREATED,
)
async def upload_document(
    file: UploadFile = File(...),
    category: str = Form(...),
    title: str = Form(...),
    employeeId: Optional[str] = Form(None),
    expiryDate: Optional[str] = Form(None),
    user: dict = Depends(get_current_user),
):
    """
    Upload a real employee document.

    The file itself is stored under:
        uploads/documents/

    Metadata is stored in MongoDB.
    """

    check_permission(
        user,
        Permission.DOCUMENT_VIEW_SELF,
    )

    db = get_database()

    # -----------------------------------------------------
    # Determine employee
    # -----------------------------------------------------

    if user["role"] == Role.EMPLOYEE:
        # Employees may only upload for themselves.
        employee = await db.employees.find_one(
            {"userId": user["user_id"]}
        )

        if not employee:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Employee record not found.",
            )

        employeeId = str(employee["_id"])

    else:
        if not employeeId:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="employeeId is required.",
            )

        employee = await get_employee(
            db,
            employeeId,
        )

        if not employee:
            raise HTTPException(
                status_code=status.HTTP_404_NOT_FOUND,
                detail="Employee not found.",
            )

    # -----------------------------------------------------
    # Validate file
    # -----------------------------------------------------

    if not file.filename:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="A file must be selected.",
        )

    # 20 MB maximum file size.
    MAX_FILE_SIZE = 20 * 1024 * 1024

    contents = await file.read()

    if len(contents) > MAX_FILE_SIZE:
        raise HTTPException(
            status_code=status.HTTP_413_REQUEST_ENTITY_TOO_LARGE,
            detail="File size cannot exceed 20 MB.",
        )

    # -----------------------------------------------------
    # Generate safe storage filename
    # -----------------------------------------------------

    original_filename = file.filename

    extension = Path(
        original_filename
    ).suffix.lower()

    stored_filename = (
        f"{uuid.uuid4().hex}{extension}"
    )

    file_path = UPLOAD_DIR / stored_filename

    try:
        with open(file_path, "wb") as output_file:
            output_file.write(contents)

    except Exception as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Could not save uploaded file: {exc}",
        )

    # -----------------------------------------------------
    # Employee information
    # -----------------------------------------------------

    employee_name = (
        f"{employee.get('firstName', '')} "
        f"{employee.get('lastName', '')}"
    ).strip()

    employee_code = employee.get(
        "employeeCode",
        "",
    )

    department = employee.get(
        "department",
        "",
    )

    # -----------------------------------------------------
    # Document metadata
    # -----------------------------------------------------

    document_id = ObjectId()

    now = datetime.utcnow().isoformat()

    document = {
        "_id": document_id,

        "employeeId": employeeId,

        "employeeName": employee_name,

        "employeeCode": employee_code,

        "department": department,

        "category": category,

        "title": title,

        "fileName": original_filename,

        "storedFileName": stored_filename,

        "fileType": file.content_type or extension,

        "fileSize": (
            f"{len(contents) / (1024 * 1024):.2f} MB"
            if len(contents) >= 1024 * 1024
            else f"{len(contents) / 1024:.1f} KB"
        ),

        "fileUrl": (
            f"/api/documents/{document_id}/download"
        ),

        "expiryDate": expiryDate,

        "uploadedBy": user["email"],

        "uploadedUserId": user["user_id"],

        "uploadedAt": now,

        "status": "PENDING",

        "verifiedBy": None,

        "verifiedAt": None,

        "rejectionReason": None,
    }

    await db.documents.insert_one(document)

    return {
        "success": True,
        "document": serialize_document(
            document
        ),
    }


# ---------------------------------------------------------
# GET /api/documents/{document_id}/download
# ---------------------------------------------------------

@router.get(
    "/{document_id}/download"
)
async def download_document(
    document_id: str,
    user: dict = Depends(get_current_user),
):
    """
    View/download the actual stored document.
    """

    check_permission(
        user,
        Permission.DOCUMENT_VIEW_SELF,
    )

    db = get_database()

    if not ObjectId.is_valid(document_id):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid document ID.",
        )

    document = await db.documents.find_one(
        {"_id": ObjectId(document_id)}
    )

    if not document:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Document not found.",
        )

    # Employee can only access own documents.
    if user["role"] == Role.EMPLOYEE:
        if (
            document.get("uploadedUserId")
            != user["user_id"]
        ):
            raise HTTPException(
                status_code=status.HTTP_403_FORBIDDEN,
                detail="You cannot access this document.",
            )

    stored_filename = document.get(
        "storedFileName"
    )

    if not stored_filename:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Stored file information is missing.",
        )

    file_path = UPLOAD_DIR / stored_filename

    if not file_path.exists():
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Physical document file was not found.",
        )

    return FileResponse(
        path=str(file_path),
        filename=document.get(
            "fileName",
            stored_filename,
        ),
        media_type=document.get(
            "fileType",
            "application/octet-stream",
        ),
    )


