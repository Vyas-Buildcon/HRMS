# ---------------------------------------------------------

@router.post(
    "/{document_id}/verify"
)
async def verify_document(
    document_id: str,
    user: dict = Depends(get_current_user),
):
    """
    Verify a document.

    Only roles with DOCUMENT_VERIFY can perform this action.
    """

    check_permission(
        user,
        Permission.DOCUMENT_VERIFY,
    )

    db = get_database()

    if not ObjectId.is_valid(document_id):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid document ID.",
        )

    document = await db.documents.find_one(
        {"_id": ObjectId(document_id)}
    )

    if not document:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Document not found.",
        )

    now = datetime.utcnow().isoformat()

    await db.documents.update_one(
        {"_id": ObjectId(document_id)},
        {
            "$set": {
                "status": "VERIFIED",
                "verifiedBy": user["email"],
                "verifiedAt": now,
                "rejectionReason": None,
            }
        },
    )

    updated = await db.documents.find_one(
        {"_id": ObjectId(document_id)}
    )

    return {
        "success": True,
        "document": serialize_document(
            updated
        ),
    }


# ---------------------------------------------------------
# POST /api/documents/{document_id}/reject
# ---------------------------------------------------------

@router.post(
    "/{document_id}/reject"
)
async def reject_document(
    document_id: str,
    reason: str = Form(...),
    user: dict = Depends(get_current_user),
):
    """
    Reject a document and record the reason.
    """

    check_permission(
        user,
        Permission.DOCUMENT_VERIFY,
    )

    db = get_database()

    if not ObjectId.is_valid(document_id):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid document ID.",
        )

    if not reason.strip():
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Rejection reason is required.",
        )

    document = await db.documents.find_one(
        {"_id": ObjectId(document_id)}
    )

    if not document:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="Document not found.",
        )

    await db.documents.update_one(
        {"_id": ObjectId(document_id)},
        {
            "$set": {
                "status": "REJECTED",
                "rejectionReason": reason.strip(),
                "verifiedBy": None,
                "verifiedAt": None,
            }
        },
    )

    updated = await db.documents.find_one(
        {"_id": ObjectId(document_id)}
    )

    return {
        "success": True,
        "document": serialize_document(
            updated
        ),
    }


